    private void btnConsultarShowLibrosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarShowLibrosActionPerformed
        // TODO add your handling code here:
        String filtro = (String) comboShowLibros.getSelectedItem();

        core.controller.utils.Response<java.util.List<Book>> response;

        // Elegir qué consulta hacer según el filtro
        if ("Libros Impresos".equals(filtro)) {
            response = bookController.obtenerLibrosPorTipo(PrintedBook.class);
        } else if ("Libros Digitales".equals(filtro)) {
            response = bookController.obtenerLibrosPorTipo(DigitalBook.class);
        } else if ("Audiolibros".equals(filtro)) {
            response = bookController.obtenerLibrosPorTipo(Audiobook.class);
        } else { // "Todos los Libros"
            response = bookController.obtenerTodosLosLibros();
        }

        if (!response.isOk()) {
            JOptionPane.showMessageDialog(
                    this,
                    response.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        java.util.List<Book> libros = response.getData();

        DefaultTableModel model = (DefaultTableModel) tblShowLibros.getModel();
        model.setRowCount(0);

        for (Book book : libros) {

            // Construir cadena de autores: "Autor1, Autor2, Autor3"
            String autores = "";
            if (book.getAuthors() != null && !book.getAuthors().isEmpty()) {
                autores = book.getAuthors().get(0).getFullname();
                for (int i = 1; i < book.getAuthors().size(); i++) {
                    autores += ", " + book.getAuthors().get(i).getFullname();
                }
            } else {
                autores = "-";
            }

            // Valores por defecto
            String ejemplares = "-";
            String paginas = "-";
            String hyperlink = "-";
            String narrador = "-";
            String duracion = "-";

            if (book instanceof PrintedBook pb) {
                ejemplares = String.valueOf(pb.getCopies());
                paginas = String.valueOf(pb.getPages());
            } else if (book instanceof DigitalBook db) {
                hyperlink = db.hasHyperlink() ? db.getHyperlink() : "No";
            } else if (book instanceof Audiobook ab) {
                narrador = ab.getNarrador().getFullname();
                duracion = String.valueOf(ab.getDuration());
            }

            model.addRow(new Object[]{
                book.getTitle(),
                autores,
                book.getIsbn(),
                book.getGenre(),
                book.getFormat(),
                book.getValue(),
                book.getPublisher().getName(),
                ejemplares,
                paginas,
                hyperlink,
                narrador,
                duracion
            });
        }
    }//GEN-LAST:event_btnConsultarShowLibrosActionPerformed

