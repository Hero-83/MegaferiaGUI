    private void btnCrearLibroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearLibroActionPerformed
        // TODO add your handling code here:

        // Debe elegir un tipo de libro
        if (!RbtnImpresoLibro.isSelected() && !RbtnDigitalLibro.isSelected() && !RbtnAudioLibro.isSelected()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Debe seleccionar un tipo de libro (Impreso, Digital o Audiolibro).",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try {
            String title = txtTituloLibro.getText().trim();
            String isbn = txtISBNLibro.getText().trim();
            String genre = (String) comboGeneroLibro.getSelectedItem();
            String format = (String) comboFormatoLibro.getSelectedItem();
            double value = Double.parseDouble(txtValorLibro.getText().trim());

            // Editorial: "Nombre (NIT)"
            String publisherData = (String) comboEditorialLibro.getSelectedItem();
            if (publisherData == null || publisherData.equals("Seleccione uno...")) {
                JOptionPane.showMessageDialog(
                        this,
                        "Debe seleccionar una editorial.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }
            String publisherNit = publisherData.split(" ")[1]
                    .replace("(", "")
                    .replace(")", "");

            // Autores desde txtAreaLibro: líneas "id - Nombre Apellido"
            String[] authorsLines = txtAreaLibro.getText().split("\n");
            java.util.List<Long> authorIds = new java.util.ArrayList<>();

            for (String line : authorsLines) {
                line = line.trim();
                if (line.isEmpty()) {
                    continue;
                }

                String[] parts = line.split(" - ");
                long authorId = Long.parseLong(parts[0]);

                if (!authorIds.contains(authorId)) {
                    authorIds.add(authorId);
                }
            }

            if (authorIds.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "Debe agregar al menos un autor al libro.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            core.controller.utils.Response<Void> response;

            // ===== Libro Impreso =====
            if (RbtnImpresoLibro.isSelected()) {

                int pages = Integer.parseInt(txtNroPaginasLibro.getText().trim());
                int copies = Integer.parseInt(txtNroEjemplaresLibro.getText().trim());

                response = bookController.crearLibroImpreso(
                        title,
                        authorIds,
                        isbn,
                        genre,
                        format,
                        value,
                        publisherNit,
                        pages,
                        copies
                );

                // ===== Libro Digital =====
            } else if (RbtnDigitalLibro.isSelected()) {

                String hyperlink = txtHipervinculoLibro.getText().trim();

                response = bookController.crearLibroDigital(
                        title,
                        authorIds,
                        isbn,
                        genre,
                        format,
                        value,
                        publisherNit,
                        hyperlink
                );

                // ===== Audiolibro =====
            } else { // RbtnAudioLibro

                int duration = Integer.parseInt(txtDuracionLibro.getText().trim());

                String narratorItem = (String) comboNarradorLibro.getSelectedItem();
                if (narratorItem == null || narratorItem.equals("Seleccione uno...")) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Debe seleccionar un narrador para el audiolibro.",
                            "Error",
                            JOptionPane.ERROR_MESSAGE
                    );
                    return;
                }

                long narratorId = Long.parseLong(narratorItem.split(" - ")[0]);

                response = bookController.crearAudiolibro(
                        title,
                        authorIds,
                        isbn,
                        genre,
                        format,
                        value,
                        publisherNit,
                        duration,
                        narratorId
                );
            }

            // Manejar respuesta del controlador
            if (response.isOk()) {
                JOptionPane.showMessageDialog(this, response.getMessage());

                // Limpiar campos
                txtTituloLibro.setText("");
                txtISBNLibro.setText("");
                txtValorLibro.setText("");
                txtHipervinculoLibro.setText("");
                txtNroPaginasLibro.setText("");
                txtNroEjemplaresLibro.setText("");
                txtDuracionLibro.setText("");
                txtAreaLibro.setText("");

                RbtnImpresoLibro.setSelected(false);
                RbtnDigitalLibro.setSelected(false);
                RbtnAudioLibro.setSelected(false);

                // actualizarTablaLibros();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        response.getMessage(),
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Hay campos numericos invalidos (valor, paginas, ejemplares o duracion).",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnCrearLibroActionPerformed

